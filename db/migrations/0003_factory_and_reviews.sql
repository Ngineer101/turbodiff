CREATE TABLE app.cockpit_comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  feature_id bigint NOT NULL REFERENCES app.features (id) ON DELETE CASCADE,
  path text NOT NULL,
  line integer NOT NULL CHECK (line > 0),
  side text NOT NULL DEFAULT 'additions' CHECK (side IN ('additions', 'deletions')),
  body text NOT NULL,
  author text NOT NULL,
  author_id bigint,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'dispatched')),
  fix_attempt_id bigint REFERENCES app.fix_attempts (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX cockpit_comments_feature_idx ON app.cockpit_comments (feature_id, id);
CREATE INDEX cockpit_comments_fix_attempt_idx ON app.cockpit_comments (fix_attempt_id)
  WHERE fix_attempt_id IS NOT NULL;

CREATE TABLE app.chat_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  feature_id bigint NOT NULL REFERENCES app.features (id) ON DELETE CASCADE,
  role text NOT NULL CHECK (role IN ('user', 'assistant')),
  body text NOT NULL,
  author text,
  author_id bigint,
  status text NOT NULL DEFAULT 'done' CHECK (status IN ('queued', 'running', 'done', 'failed')),
  outcome text CHECK (outcome IS NULL OR outcome IN ('changed', 'no_changes', 'tests_failed')),
  commit_sha text,
  error text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX chat_messages_feature_idx ON app.chat_messages (feature_id, id);
CREATE UNIQUE INDEX chat_messages_one_pending_user_idx ON app.chat_messages (feature_id)
  WHERE role = 'user' AND status IN ('queued', 'running');

CREATE TABLE app.automations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repository_id bigint NOT NULL REFERENCES app.repositories (id) ON DELETE CASCADE,
  name text NOT NULL,
  prompt text NOT NULL,
  schedule_kind text NOT NULL CHECK (schedule_kind IN ('hourly', 'daily', 'weekly')),
  time_of_day time,
  day_of_week smallint CHECK (day_of_week BETWEEN 0 AND 6),
  enabled smallint NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
  next_run_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT automations_schedule_shape CHECK (
    (schedule_kind = 'hourly' AND time_of_day IS NULL AND day_of_week IS NULL)
    OR (schedule_kind = 'daily' AND time_of_day IS NOT NULL AND day_of_week IS NULL)
    OR (schedule_kind = 'weekly' AND time_of_day IS NOT NULL AND day_of_week IS NOT NULL)
  )
);

CREATE INDEX automations_repository_idx ON app.automations (repository_id, id);
CREATE INDEX automations_due_idx ON app.automations (next_run_at) WHERE enabled = 1;

CREATE TABLE app.automation_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  automation_id bigint NOT NULL REFERENCES app.automations (id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'running' CHECK (
    status IN ('running', 'pr_opened', 'no_changes', 'checks_failed', 'failed')
  ),
  pr_number integer CHECK (pr_number IS NULL OR pr_number > 0),
  commit_sha text,
  error text,
  input_tokens bigint NOT NULL DEFAULT 0 CHECK (input_tokens >= 0),
  output_tokens bigint NOT NULL DEFAULT 0 CHECK (output_tokens >= 0),
  cache_read_tokens bigint NOT NULL DEFAULT 0 CHECK (cache_read_tokens >= 0),
  cache_write_tokens bigint NOT NULL DEFAULT 0 CHECK (cache_write_tokens >= 0),
  cost_usd numeric(20, 10) NOT NULL DEFAULT 0 CHECK (cost_usd >= 0),
  model text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX automation_runs_automation_idx ON app.automation_runs (automation_id, created_at DESC);
CREATE UNIQUE INDEX automation_runs_one_running_idx ON app.automation_runs (automation_id)
  WHERE status = 'running';

CREATE TABLE app.agent_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (
    kind IN ('plan_analyze', 'plan_refine', 'generate', 'verify', 'fix', 'automation', 'chat', 'resolve_conflict')
  ),
  plan_id bigint REFERENCES app.plans (id) ON DELETE CASCADE,
  feature_id bigint REFERENCES app.features (id) ON DELETE CASCADE,
  fix_attempt_id bigint REFERENCES app.fix_attempts (id) ON DELETE CASCADE,
  automation_run_id bigint REFERENCES app.automation_runs (id) ON DELETE CASCADE,
  log_key text NOT NULL,
  success smallint NOT NULL CHECK (success IN (0, 1)),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT agent_runs_owner CHECK (
    num_nonnulls(plan_id, feature_id, fix_attempt_id, automation_run_id) >= 1
  )
);

CREATE INDEX agent_runs_plan_idx ON app.agent_runs (plan_id) WHERE plan_id IS NOT NULL;
CREATE INDEX agent_runs_feature_idx ON app.agent_runs (feature_id) WHERE feature_id IS NOT NULL;
CREATE INDEX agent_runs_fix_attempt_idx ON app.agent_runs (fix_attempt_id) WHERE fix_attempt_id IS NOT NULL;
CREATE INDEX agent_runs_automation_idx ON app.agent_runs (automation_run_id)
  WHERE automation_run_id IS NOT NULL;
