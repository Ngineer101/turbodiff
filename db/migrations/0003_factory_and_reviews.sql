CREATE TABLE app.todos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  installation_id bigint NOT NULL REFERENCES app.installations (id) ON DELETE CASCADE,
  title text NOT NULL,
  notes text,
  created_by_login text,
  created_by_id bigint,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app.plans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repository_id bigint NOT NULL REFERENCES app.repositories (id) ON DELETE CASCADE,
  todo_id bigint REFERENCES app.todos (id) ON DELETE SET NULL,
  title text NOT NULL,
  requirements text NOT NULL,
  analysis text,
  questions jsonb,
  answers jsonb,
  plan text,
  acceptance jsonb,
  status text NOT NULL DEFAULT 'analyzing' CHECK (
    status IN ('analyzing', 'awaiting_answers', 'refining', 'plan_ready', 'approving', 'approved', 'failed')
  ),
  error text,
  created_by_login text,
  created_by_id bigint,
  tier text,
  archived smallint NOT NULL DEFAULT 0 CHECK (archived IN (0, 1)),
  feedback text,
  attachments jsonb,
  runner_model text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT plans_todo_unique UNIQUE (todo_id)
);

CREATE INDEX plans_repository_created_idx ON app.plans (repository_id, created_at DESC);
CREATE INDEX plans_active_idx ON app.plans (repository_id, id DESC) WHERE archived = 0;

CREATE TABLE app.features (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repository_id bigint NOT NULL REFERENCES app.repositories (id) ON DELETE CASCADE,
  plan_id bigint REFERENCES app.plans (id) ON DELETE SET NULL,
  title text NOT NULL,
  spec text NOT NULL,
  acceptance jsonb,
  branch text,
  pr_number integer CHECK (pr_number > 0),
  status text NOT NULL DEFAULT 'queued' CHECK (
    status IN ('queued', 'generating', 'pr_opened', 'no_changes', 'checks_failed', 'failed', 'merged', 'pr_closed', 'abandoned')
  ),
  error text,
  author_login text,
  author_id bigint,
  coauthor_login text,
  coauthor_id bigint,
  run_started_at timestamptz,
  tier text,
  input_tokens bigint NOT NULL DEFAULT 0 CHECK (input_tokens >= 0),
  output_tokens bigint NOT NULL DEFAULT 0 CHECK (output_tokens >= 0),
  cache_read_tokens bigint NOT NULL DEFAULT 0 CHECK (cache_read_tokens >= 0),
  cache_write_tokens bigint NOT NULL DEFAULT 0 CHECK (cache_write_tokens >= 0),
  cost_usd numeric(20, 10) NOT NULL DEFAULT 0 CHECK (cost_usd >= 0),
  model text,
  runner_model text,
  change_request_id bigint,
  criteria_conflict smallint NOT NULL DEFAULT 0 CHECK (criteria_conflict IN (0, 1)),
  acceptance_updated_at timestamptz,
  proposed_acceptance jsonb,
  chat_session_id text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT features_plan_repository_unique UNIQUE (plan_id, repository_id)
);

ALTER TABLE app.plans ADD COLUMN feature_id bigint REFERENCES app.features (id) ON DELETE SET NULL;
ALTER TABLE app.todos ADD COLUMN plan_id bigint REFERENCES app.plans (id) ON DELETE SET NULL;
CREATE INDEX plans_feature_idx ON app.plans (feature_id) WHERE feature_id IS NOT NULL;
CREATE UNIQUE INDEX todos_plan_unique ON app.todos (plan_id) WHERE plan_id IS NOT NULL;

CREATE INDEX todos_installation_unplanned_idx ON app.todos (installation_id, id DESC)
  WHERE plan_id IS NULL;
CREATE INDEX features_repository_created_idx ON app.features (repository_id, id DESC);
CREATE INDEX features_repository_pr_idx ON app.features (repository_id, pr_number, id DESC)
  WHERE pr_number IS NOT NULL;
CREATE INDEX features_plan_idx ON app.features (plan_id) WHERE plan_id IS NOT NULL;
CREATE INDEX features_open_pr_idx ON app.features (repository_id, pr_number)
  WHERE status = 'pr_opened' AND pr_number IS NOT NULL;
CREATE INDEX features_generating_created_idx ON app.features (created_at)
  WHERE status = 'generating';

