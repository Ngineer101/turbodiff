  PRIMARY KEY (todo_id, repository_id),
  CONSTRAINT todo_repositories_position_unique UNIQUE (todo_id, position)
);

CREATE INDEX todo_repositories_repository_idx ON app.todo_repositories (repository_id);

CREATE TABLE app.plan_repositories (
  plan_id bigint NOT NULL REFERENCES app.plans (id) ON DELETE CASCADE,
  repository_id bigint NOT NULL REFERENCES app.repositories (id) ON DELETE CASCADE,
  position smallint NOT NULL CHECK (position BETWEEN 0 AND 2),
  PRIMARY KEY (plan_id, repository_id),
  CONSTRAINT plan_repositories_position_unique UNIQUE (plan_id, position)
);

CREATE INDEX plan_repositories_repository_idx ON app.plan_repositories (repository_id);

CREATE TABLE app.reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repository_id bigint NOT NULL,
  installation_id bigint NOT NULL,
  pr_number integer NOT NULL CHECK (pr_number > 0),
  trigger_event text NOT NULL,
  status text NOT NULL DEFAULT 'completed' CHECK (status IN ('running', 'completed', 'failed')),
  completed_at timestamptz,
  review_url text,
  input_tokens bigint NOT NULL DEFAULT 0 CHECK (input_tokens >= 0),
  output_tokens bigint NOT NULL DEFAULT 0 CHECK (output_tokens >= 0),
  cache_read_tokens bigint NOT NULL DEFAULT 0 CHECK (cache_read_tokens >= 0),
  cache_write_tokens bigint NOT NULL DEFAULT 0 CHECK (cache_write_tokens >= 0),
  cost_usd numeric(20, 10) NOT NULL DEFAULT 0 CHECK (cost_usd >= 0),
  model text,
  agent_slug text,
  agent_instance_id text,
  risk_tier text CHECK (risk_tier IS NULL OR risk_tier IN ('trivial', 'lite', 'full')),
  findings_count integer CHECK (findings_count IS NULL OR findings_count >= 0),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT reviews_repository_tenant_fk
    FOREIGN KEY (repository_id, installation_id)
    REFERENCES app.repositories (id, installation_id) ON DELETE CASCADE,
  CONSTRAINT reviews_completion_shape CHECK (
    (status = 'running' AND completed_at IS NULL) OR status <> 'running'
  )
);

CREATE INDEX reviews_installation_time_idx ON app.reviews (installation_id, created_at DESC);
CREATE INDEX reviews_repository_installation_idx ON app.reviews (repository_id, installation_id);
CREATE INDEX reviews_repo_pr_idx ON app.reviews (repository_id, pr_number, id DESC);
CREATE INDEX reviews_agent_instance_idx ON app.reviews (agent_instance_id);
CREATE UNIQUE INDEX reviews_one_running_instance_idx ON app.reviews (agent_instance_id)
  WHERE status = 'running' AND agent_instance_id IS NOT NULL;
CREATE INDEX reviews_running_installation_idx ON app.reviews (installation_id, created_at)
  WHERE status = 'running';

CREATE TABLE app.fix_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
