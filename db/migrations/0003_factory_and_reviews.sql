CREATE INDEX fix_attempts_pr_idx ON app.fix_attempts (repository_id, pr_number, id DESC);
CREATE UNIQUE INDEX fix_attempts_one_running_idx ON app.fix_attempts (repository_id, pr_number)
  WHERE status = 'running';

