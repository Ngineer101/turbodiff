CREATE TABLE auth."organization" (
  "id" text PRIMARY KEY,
  "name" text NOT NULL,
  "slug" text NOT NULL UNIQUE,
  "logo" text,
  "metadata" text,
  "createdAt" timestamptz NOT NULL,
  "installationId" bigint NOT NULL UNIQUE REFERENCES app.installations (id) ON DELETE CASCADE
);

ALTER TABLE auth."session"
  ADD CONSTRAINT session_active_organization_fk
  FOREIGN KEY ("activeOrganizationId") REFERENCES auth."organization" ("id") ON DELETE SET NULL;

CREATE TABLE auth."member" (
  "id" text PRIMARY KEY,
  "organizationId" text NOT NULL REFERENCES auth."organization" ("id") ON DELETE CASCADE,
  "userId" text NOT NULL REFERENCES auth."user" ("id") ON DELETE CASCADE,
  "role" text NOT NULL DEFAULT 'member' CHECK ("role" IN ('owner', 'admin', 'member')),
  "createdAt" timestamptz NOT NULL,
  CONSTRAINT member_organization_user_unique UNIQUE ("organizationId", "userId")
);

CREATE INDEX member_user_id_idx ON auth."member" ("userId");

CREATE TABLE auth."invitation" (
  "id" text PRIMARY KEY,
  "organizationId" text NOT NULL REFERENCES auth."organization" ("id") ON DELETE CASCADE,
  "email" text NOT NULL,
  "role" text NOT NULL CHECK ("role" IN ('owner', 'admin', 'member')),
  "status" text NOT NULL DEFAULT 'pending' CHECK ("status" IN ('pending', 'accepted', 'rejected', 'canceled')),
  "expiresAt" timestamptz NOT NULL,
  "createdAt" timestamptz NOT NULL,
  "inviterId" text NOT NULL REFERENCES auth."user" ("id") ON DELETE CASCADE
);

CREATE INDEX invitation_organization_idx ON auth."invitation" ("organizationId", "status");
CREATE INDEX invitation_inviter_idx ON auth."invitation" ("inviterId");
CREATE INDEX invitation_email_status_idx ON auth."invitation" ("email", "status");
CREATE UNIQUE INDEX invitation_pending_email_unique
  ON auth."invitation" ("organizationId", lower("email")) WHERE "status" = 'pending';

CREATE TABLE app.user_tokens (
  user_id bigint PRIMARY KEY,
  login text NOT NULL,
  refresh_ciphertext text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app.user_installation_access (
  user_id text PRIMARY KEY REFERENCES auth."user" ("id") ON DELETE CASCADE,
  installation_ids bigint[] NOT NULL DEFAULT '{}',
  verified_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT user_installation_access_no_null_ids
    CHECK (array_position(installation_ids, NULL) IS NULL)
